import PDFDocument from "pdfkit";
import { ExtractedPage, ContentBlock } from "./extractor";

export interface PDFGenerationOptions {
  siteTitle: string;
  sourceUrl: string;
  pages: ExtractedPage[];
  documentTitle?: string;
}

export interface PDFGenerationResult {
  buffer: Buffer;
  pageCount: number;
}

/**
 * Generates a structured, clean, searchable PDF document from extracted documentation pages.
 */
export async function generateDocumentationPDF(
  options: PDFGenerationOptions
): Promise<PDFGenerationResult> {
  const { siteTitle, sourceUrl, pages, documentTitle } = options;

  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size: "A4",
        margins: { top: 54, bottom: 54, left: 54, right: 54 },
        bufferPages: true,
        info: {
          Title: documentTitle || `${siteTitle} — Documentation Manual`,
          Author: "Docu (https://github.com/sanstack256/Docu)",
          Subject: `Offline Documentation for ${siteTitle}`,
          Keywords: "documentation, manual, offline, pdf",
          CreationDate: new Date(),
        },
      });

      let recordedPageCount = 0;

      const chunks: Buffer[] = [];
      doc.on("data", (chunk: Buffer) => chunks.push(chunk));
      doc.on("end", () => {
        const buffer = Buffer.concat(chunks);
        resolve({
          buffer,
          pageCount: recordedPageCount,
        });
      });
      doc.on("error", (err: Error) => reject(err));

      const pageWidth = doc.page.width - doc.page.margins.left - doc.page.margins.right;

      // ==========================================
      // 1. COVER / TITLE PAGE
      // ==========================================
      doc.moveDown(4);

      // Accent pill
      doc.roundedRect(doc.x, doc.y, 80, 20, 4).fill("#ebf8ff");
      doc.fillColor("#2b6cb0").fontSize(9).font("Helvetica-Bold").text("OFFLINE MANUAL", doc.x + 8, doc.y + 6);
      doc.moveDown(2);

      // Main Title
      const displayTitle = documentTitle || siteTitle;
      doc.fillColor("#1a202c").fontSize(28).font("Helvetica-Bold").text(displayTitle, { width: pageWidth });
      doc.moveDown(0.5);

      // Subtitle
      doc.fillColor("#718096").fontSize(13).font("Helvetica").text("Compiled Documentation Reference", { width: pageWidth });
      doc.moveDown(2);

      // Divider line
      doc.strokeColor("#e2e8f0").lineWidth(1).moveTo(doc.x, doc.y).lineTo(doc.x + pageWidth, doc.y).stroke();
      doc.moveDown(2);

      // Metadata block
      doc.fillColor("#4a5568").fontSize(10).font("Helvetica-Bold").text("Source URL: ");
      doc.fillColor("#3182ce").fontSize(9.5).font("Helvetica").text(sourceUrl, { link: sourceUrl, underline: true });
      doc.moveDown(0.5);

      doc.fillColor("#4a5568").fontSize(10).font("Helvetica-Bold").text("Compiled: ");
      doc.fillColor("#718096").fontSize(9.5).font("Helvetica").text(new Date().toUTCString());
      doc.moveDown(0.5);

      doc.fillColor("#4a5568").fontSize(10).font("Helvetica-Bold").text("Pages Included: ");
      doc.fillColor("#718096").fontSize(9.5).font("Helvetica").text(`${pages.length} documentation sections`);
      doc.moveDown(4);

      // Brand tag
      doc.fillColor("#a0aec0").fontSize(9).font("Helvetica").text("Generated by Docu — Deterministic Documentation Converter", {
        align: "center",
        width: pageWidth,
      });

      // ==========================================
      // 2. TABLE OF CONTENTS
      // ==========================================
      doc.addPage();
      const tocPageIndex = doc.bufferedPageRange().count - 1;

      doc.fillColor("#1a202c").fontSize(20).font("Helvetica-Bold").text("Table of Contents", { width: pageWidth });
      doc.moveDown(0.5);
      doc.strokeColor("#e2e8f0").lineWidth(1).moveTo(doc.x, doc.y).lineTo(doc.x + pageWidth, doc.y).stroke();
      doc.moveDown(1.5);

      const pageStartIndices: number[] = [];

      // ==========================================
      // 3. DOCUMENTATION CONTENT PAGES
      // ==========================================
      for (let i = 0; i < pages.length; i++) {
        const page = pages[i];
        doc.addPage();
        const currentPageNum = doc.bufferedPageRange().count;
        pageStartIndices.push(currentPageNum);

        // Section Title
        doc.fillColor("#2b6cb0").fontSize(18).font("Helvetica-Bold").text(page.title, { width: pageWidth });
        doc.moveDown(0.3);

        // Source link for this page
        doc.fillColor("#a0aec0").fontSize(8.5).font("Helvetica").text(page.url, {
          link: page.url,
          underline: true,
          width: pageWidth,
        });
        doc.moveDown(0.5);

        // Section divider
        doc.strokeColor("#edf2f7").lineWidth(1).moveTo(doc.x, doc.y).lineTo(doc.x + pageWidth, doc.y).stroke();
        doc.moveDown(1);

        // Render Content Blocks
        for (const block of page.blocks) {
          renderBlock(doc, block, pageWidth);
        }
      }

      // ==========================================
      // 4. POPULATE TABLE OF CONTENTS
      // ==========================================
      doc.switchToPage(tocPageIndex);
      doc.y = 110; // Position below TOC heading

      for (let i = 0; i < pages.length; i++) {
        const page = pages[i];
        const targetPage = pageStartIndices[i];

        if (doc.y > doc.page.height - 80) {
          doc.addPage();
          doc.y = 60;
        }

        const itemY = doc.y;
        doc.fillColor("#2d3748").fontSize(10.5).font("Helvetica").text(
          `${i + 1}.  ${page.title}`,
          doc.page.margins.left,
          itemY,
          { width: pageWidth - 40, lineBreak: false }
        );

        doc.fillColor("#718096").fontSize(10).font("Helvetica-Bold").text(
          `${targetPage}`,
          doc.page.width - doc.page.margins.right - 30,
          itemY,
          { align: "right", width: 30 }
        );

        doc.moveDown(0.7);
      }

      // ==========================================
      // 5. RUNNING HEADERS & FOOTERS
      // ==========================================
      const totalPages = doc.bufferedPageRange().count;
      recordedPageCount = totalPages;
      for (let p = 0; p < totalPages; p++) {
        doc.switchToPage(p);

        // Skip header/footer on title page
        if (p === 0) continue;

        // Running Header
        doc.fillColor("#a0aec0").fontSize(8).font("Helvetica").text(
          siteTitle.toUpperCase(),
          doc.page.margins.left,
          25,
          { width: pageWidth, align: "left" }
        );
        doc.strokeColor("#f0f4f8").lineWidth(0.5).moveTo(doc.page.margins.left, 38).lineTo(doc.page.margins.left + pageWidth, 38).stroke();

        // Running Footer
        doc.strokeColor("#f0f4f8").lineWidth(0.5).moveTo(doc.page.margins.left, doc.page.height - 40).lineTo(doc.page.margins.left + pageWidth, doc.page.height - 40).stroke();
        doc.fillColor("#a0aec0").fontSize(8).font("Helvetica").text(
          `Page ${p + 1} of ${totalPages}`,
          doc.page.margins.left,
          doc.page.height - 30,
          { width: pageWidth, align: "right" }
        );
        doc.fillColor("#cbd5e0").fontSize(8).font("Helvetica").text(
          "Docu Offline Manual",
          doc.page.margins.left,
          doc.page.height - 30,
          { width: pageWidth, align: "left" }
        );
      }

      doc.end();
    } catch (err: unknown) {
      reject(err);
    }
  });
}

function renderBlock(doc: typeof PDFDocument.prototype, block: ContentBlock, pageWidth: number): void {
  // Check if nearing page bottom
  if (doc.y > doc.page.height - 90) {
    doc.addPage();
  }

  switch (block.type) {
    case "heading": {
      const sizes: Record<number, number> = { 1: 16, 2: 13.5, 3: 12, 4: 10.5, 5: 10, 6: 9.5 };
      const fontSize = sizes[block.level] || 11;
      doc.moveDown(0.8);
      doc.fillColor("#1a202c").fontSize(fontSize).font("Helvetica-Bold").text(block.text, { width: pageWidth });
      doc.moveDown(0.4);
      break;
    }

    case "paragraph": {
      doc.fillColor("#2d3748").fontSize(10).font("Helvetica").text(block.text, {
        width: pageWidth,
        lineGap: 2.5,
      });
      doc.moveDown(0.6);
      break;
    }

    case "code": {
      doc.moveDown(0.4);
      const codeStartX = doc.x;
      const codeStartY = doc.y;
      const codeLines = block.code.split("\n");

      // Estimate box height
      doc.fontSize(8.5).font("Courier");
      let contentHeight = 0;
      for (const line of codeLines) {
        contentHeight += doc.heightOfString(line || " ", { width: pageWidth - 20 }) + 1.5;
      }
      contentHeight = Math.max(contentHeight + 16, 24);

      // If code box doesn't fit on this page, create a new page
      if (doc.y + Math.min(contentHeight, 150) > doc.page.height - 70) {
        doc.addPage();
      }

      const actualStartY = doc.y;

      // Draw background box
      doc.roundedRect(codeStartX, actualStartY, pageWidth, contentHeight, 4).fill("#f7fafc");
      doc.roundedRect(codeStartX, actualStartY, pageWidth, contentHeight, 4).strokeColor("#e2e8f0").lineWidth(1).stroke();

      // Draw language tag if specified
      if (block.language) {
        doc.fillColor("#a0aec0").fontSize(7).font("Helvetica-Bold").text(
          block.language.toUpperCase(),
          codeStartX + pageWidth - 60,
          actualStartY + 6,
          { width: 50, align: "right" }
        );
      }

      // Render code text
      doc.fillColor("#1a202c").fontSize(8.5).font("Courier");
      let currentY = actualStartY + 10;
      for (const line of codeLines) {
        doc.text(line || " ", codeStartX + 10, currentY, {
          width: pageWidth - 20,
          lineBreak: true,
        });
        currentY += doc.heightOfString(line || " ", { width: pageWidth - 20 }) + 1.5;
      }

      doc.y = actualStartY + contentHeight;
      doc.moveDown(0.6);
      break;
    }

    case "list": {
      doc.moveDown(0.3);
      for (let i = 0; i < block.items.length; i++) {
        const bullet = block.ordered ? `${i + 1}.` : "•";
        const itemText = block.items[i];

        doc.fillColor("#4a5568").fontSize(10).font("Helvetica-Bold").text(
          bullet,
          doc.x + 8,
          doc.y,
          { width: 20, lineBreak: false }
        );
        doc.fillColor("#2d3748").fontSize(10).font("Helvetica").text(
          itemText,
          doc.x + 28,
          doc.y,
          { width: pageWidth - 36, lineGap: 2 }
        );
        doc.moveDown(0.3);
      }
      doc.moveDown(0.5);
      break;
    }

    case "callout": {
      doc.moveDown(0.5);
      const calloutColors: Record<string, { bg: string; border: string; title: string }> = {
        note: { bg: "#ebf8ff", border: "#3182ce", title: "NOTE" },
        tip: { bg: "#f0fff4", border: "#38a169", title: "TIP" },
        warning: { bg: "#fffaf0", border: "#dd6b20", title: "WARNING" },
        caution: { bg: "#fff5f5", border: "#e53e3e", title: "CAUTION" },
        info: { bg: "#ebf8ff", border: "#3182ce", title: "INFO" },
      };

      const theme = calloutColors[block.variant] || calloutColors.note;
      const boxX = doc.x;
      const boxY = doc.y;

      doc.fontSize(9.5).font("Helvetica");
      const textHeight = doc.heightOfString(block.text, { width: pageWidth - 24 });
      const boxHeight = textHeight + 28;

      if (boxY + boxHeight > doc.page.height - 70) {
        doc.addPage();
      }

      const finalY = doc.y;
      doc.roundedRect(boxX, finalY, pageWidth, boxHeight, 3).fill(theme.bg);
      doc.rect(boxX, finalY, 4, boxHeight).fill(theme.border);

      doc.fillColor(theme.border).fontSize(8).font("Helvetica-Bold").text(theme.title, boxX + 12, finalY + 8);
      doc.fillColor("#2d3748").fontSize(9.5).font("Helvetica").text(block.text, boxX + 12, finalY + 20, {
        width: pageWidth - 24,
        lineGap: 2,
      });

      doc.y = finalY + boxHeight;
      doc.moveDown(0.6);
      break;
    }

    case "table": {
      doc.moveDown(0.6);
      const allRows = block.headers.length > 0 ? [block.headers, ...block.rows] : block.rows;
      if (allRows.length === 0) break;

      const colCount = Math.max(...allRows.map((r) => r.length), 1);
      const colWidth = pageWidth / colCount;

      let tableY = doc.y;
      if (tableY + 60 > doc.page.height - 70) {
        doc.addPage();
        tableY = doc.y;
      }

      for (let r = 0; r < allRows.length; r++) {
        const row = allRows[r];
        const isHeader = r === 0 && block.headers.length > 0;

        // Calculate max cell height in row
        doc.fontSize(8.5).font(isHeader ? "Helvetica-Bold" : "Helvetica");
        let maxRowHeight = 18;
        for (const cell of row) {
          const h = doc.heightOfString(cell, { width: colWidth - 8 }) + 8;
          if (h > maxRowHeight) maxRowHeight = h;
        }

        if (tableY + maxRowHeight > doc.page.height - 70) {
          doc.addPage();
          tableY = doc.y;
        }

        // Row background
        if (isHeader) {
          doc.rect(doc.page.margins.left, tableY, pageWidth, maxRowHeight).fill("#edf2f7");
        } else if (r % 2 === 1) {
          doc.rect(doc.page.margins.left, tableY, pageWidth, maxRowHeight).fill("#f7fafc");
        }

        // Draw cells
        for (let c = 0; c < colCount; c++) {
          const cellText = row[c] || "";
          const cellX = doc.page.margins.left + c * colWidth;

          // Cell border
          doc.rect(cellX, tableY, colWidth, maxRowHeight).strokeColor("#e2e8f0").lineWidth(0.5).stroke();

          // Cell text
          doc.fillColor(isHeader ? "#1a202c" : "#2d3748")
            .fontSize(8.5)
            .font(isHeader ? "Helvetica-Bold" : "Helvetica")
            .text(cellText, cellX + 4, tableY + 4, {
              width: colWidth - 8,
              lineGap: 1.5,
            });
        }

        tableY += maxRowHeight;
      }

      doc.y = tableY;
      doc.moveDown(0.7);
      break;
    }

    case "hr": {
      doc.moveDown(0.5);
      doc.strokeColor("#e2e8f0").lineWidth(0.5).moveTo(doc.x, doc.y).lineTo(doc.x + pageWidth, doc.y).stroke();
      doc.moveDown(0.5);
      break;
    }

    default:
      break;
  }
}
